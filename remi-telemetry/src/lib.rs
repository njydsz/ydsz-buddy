//! # Remi Telemetry - 遥测与分析模块
//!
//! ## 模块职责
//!
//! `remi-telemetry` 是 Remi 系统的遥测与可观测性子系统，负责收集、存储和查询
//! 系统运行过程中产生的分析数据与性能指标。该模块为上层业务提供统一的数据采集接口，
//! 帮助开发者和运营团队深入了解系统行为、用户交互模式以及服务健康状况。
//!
//! ## 核心功能
//!
//! - **分析数据收集（Analytics）**：记录系统中发生的关键业务事件（如线程创建/删除、
//!   Turn 开始/完成/中断、Provider 调用、检查点操作、会话生命周期等），并自动聚合
//!   生成使用统计报告。
//! - **性能指标采集（Metrics）**：支持计数器（Counter）、仪表（Gauge）、直方图（Histogram）
//!   三种标准指标类型，用于监控请求量、响应时间、活跃连接数、错误率等关键性能数据。
//! - **统一错误处理（Error）**：定义遥测子系统的专用错误类型，覆盖分析服务、指标采集、
//!   序列化及 IO 等场景，提供类型安全的错误传播机制。
//!
//! ## 使用场景
//!
//! 1. **产品分析**：追踪用户与 AI 对话线程的交互频次、Provider/模型使用分布，辅助产品决策。
//! 2. **性能监控**：实时采集响应时间分位数（P95/P99）、错误率等指标，支撑 SLA 监控与告警。
//! 3. **运维诊断**：通过事件历史回溯和指标趋势分析，快速定位系统异常根因。
//!
//! ## 模块结构
//!
//! | 子模块 | 职责 |
//! |--------|------|
//! | [`analytics`] | 分析事件定义、事件记录与使用统计聚合服务 |
//! | [`metrics`] | 性能指标类型定义、指标记录与收集器 |
//! | [`error`] | 遥测子系统统一错误类型与 Result 别名 |
//!
//! ## 架构定位
//!
//! 本 crate 位于 Remi 系统的基础设施层，向上依赖 `remi-core` 中的领域模型
//! （如 [`ThreadId`](remi_core::models::ThreadId)），向下不依赖任何业务模块，
//! 确保遥测能力可被所有上层服务无冲突地引入。
//!
//! ## 并发安全
//!
//! 所有服务内部状态均通过 `Arc<RwLock<_>>` 保护，支持在异步 Tokio 运行时中
//! 安全地跨任务共享和并发访问。

