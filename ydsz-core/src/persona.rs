    /// 根据 MBTI ID 查找对应的人格模板
    pub fn find_by_id(id: &str) -> Option<Self> {
        Self::builtin_personas()
            .into_iter()
            .find(|p| p.id.eq_ignore_ascii_case(id))
    }

    /// 构造一个新模板
    fn new(
        id: &'static str,
        name: &'static str,
        description: &'static str,
        system_prompt_suffix: &'static str,
        avatar_emoji: &'static str,
        color: &'static str,
    ) -> Self {
        Self {
            id: id.to_string(),
            name: name.to_string(),
            mbti_type: id.to_string(),
            description: description.to_string(),
            system_prompt_suffix: system_prompt_suffix.to_string(),
            avatar_emoji: avatar_emoji.to_string(),
            color: color.to_string(),
        }
    }
