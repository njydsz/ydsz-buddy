//! Remi Terminal - 终端管理模块
//!
//! 本模块负责 PTY（伪终端）终端会话的完整生命周期管理，为 IDE 提供强大的终端功能支持。
//!
//! # 核心功能
//!
//! - **终端会话管理**：创建、重启、关闭终端会话，支持多终端实例并发管理
//! - **PTY 进程封装**：跨平台的伪终端底层操作，包括进程创建、读写、大小调整
//! - **事件驱动架构**：通过广播通道实时通知终端状态变化（启动、输出、退出、错误等）
//! - **会话状态追踪**：维护终端会话的完整状态快照，包括历史记录、退出码等
//!
//! # 使用场景
//!
//! 本模块主要应用于 IDE 的终端面板功能，支持以下典型场景：
//!
//! - 用户在工作区打开多个终端标签页，每个标签页对应独立的 PTY 会话
//! - 前端通过 WebSocket 或 IPC 与后端交互，实时传输终端输入输出
//! - 终端会话与线程（Thread）绑定，支持按线程批量管理终端
//! - 终端重启时保留工作目录和环境变量配置
//!
//! # 模块结构
//!
//! - [`error`]：定义终端模块的错误类型和结果类型别名
//! - [`manager`]：终端会话管理器，负责会话的创建、写入、调整大小、清屏、重启、关闭等操作
//! - [`pty`]：底层 PTY 进程封装，提供跨平台的伪终端操作接口
//!
//! # 设计特点
//!
//! - **线程安全**：使用 `Arc<RwLock>` 保护共享状态，支持异步并发访问
//! - **事件广播**：通过 `broadcast` 通道实现一对多的事件通知机制
//! - **资源自动清理**：实现 `Drop` trait 确保 PTY 进程在销毁时正确终止
//! - **跨平台兼容**：底层使用 `portable-pty` 库，支持 Windows、Linux、macOS

pub mod error;
pub mod manager;
pub mod pty;
