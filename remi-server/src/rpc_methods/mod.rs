//! # RPC 方法注册与处理模块
//!
//! 本模块负责将所有业务 RPC 方法注册到路由器，并提供统一的服务容器来管理各业务服务的依赖。
//!
//! ## 模块结构
//!
//! - [`handlers`] - 各业务域的 RPC 方法处理器实现
//! - [`registration`] - 服务容器定义和全局方法注册入口
//!
//! ## 支持的业务域
//!
//! | 业务域 | 方法前缀 | 说明 |
//! |--------|----------|------|
//! | 编排引擎 | `orchestration.*` | 命令分发、快照查询、事件回放 |
//! | Provider | `provider.*` | 模型列表、能力查询、技能/插件管理 |
//! | Git | `git.*` | 状态查询、分支操作、提交推送 |
//! | 终端 | `terminal.*` | 终端会话的创建、写入、调整、关闭 |
//! | 工作空间 | `workspace.*` | 文件浏览、搜索、读写、删除 |
//! | 认证 | `auth.*` | 凭证交换、会话管理、配对链接 |
//! | 检查点 | `checkpoint.*` | 检查点的创建、查询、回滚、删除 |
//! | 服务器 | `server.*` | 配置更新、Provider 刷新、诊断信息 |
//! | 遥测 | `telemetry.*` | 使用统计、事件查询、指标收集 |

